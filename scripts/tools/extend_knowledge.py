# 键名与图纸/口语常用线索词不一致时重命名(否则查"高强螺栓"匹配不到"高强度螺栓")
RENAMES = {
    'materials.json': {'钢结构': {'高强度螺栓': '高强螺栓'}},
}


def _count(obj):
    """递归统计**条目数**: 含条目特征字段(特性/规则/工艺链/常见项/列项建议/口径/提示)的 dict
    记为 1 条; 其余继续下钻。v6.10 修正: 原按"专业键下一级键"估算, 层级变化会导致数字漂移。
    """
    if not isinstance(obj, dict):
        return 0
    if set(obj.keys()) & {'特性', '规则', '工艺链', '常见项', '列项建议', '口径', '规格维度'}:
        return 1
    n = 0
    for k, v in obj.items():
        if str(k).startswith('_'):
            continue
        if isinstance(v, dict):
            n += _count(v)
        elif isinstance(v, list):
            n += 1
    return n


def merge_file(fname, additions, dry=False):
    path = os.path.join(KNOW, fname)
    if not os.path.exists(path):
        return 0, 0, f'{fname} 不存在'
    with open(path, encoding='utf-8') as f:
        data = json.load(f)
    before = _count(data)
    # 键名重命名(历史键名与常用线索词不一致 — 否则查询用口语词命中不到)
    renamed = 0
    for spec, ren in RENAMES.get(fname, {}).items():
        bucket = data.get(spec)
        if isinstance(bucket, dict):
            for old, new in ren.items():
                if old in bucket and new not in bucket:
                    bucket[new] = bucket.pop(old)
                    renamed += 1
    added = 0
    for spec, items in additions.items():
        bucket = data.get(spec)
        if not isinstance(bucket, dict):
            bucket = {}
            data[spec] = bucket
        for k, v in items.items():
            if k not in bucket:
                bucket[k] = v
                added += 1
    if (added or renamed) and not dry:
        with open(path, 'w', encoding='utf-8') as f:
            json.dump(data, f, ensure_ascii=False, indent=2)
    return before, added, (f'重命名 {renamed} 个键' if renamed else '')


def main(argv=None):
    ap = argparse.ArgumentParser()
    ap.add_argument('--dry-run', action='store_true')
    args = ap.parse_args(argv)
    total_before = total_add = 0
    print(f'知识库目录: {KNOW}')
    for fname, additions in FILES.items():
        before, added, err = merge_file(fname, additions, dry=args.dry_run)
        if err:
            print(f'  {fname}: {err}')
            continue
        total_before += before
        total_add += added
        print(f'  {fname}: {before} → {before + added} 条 (+{added})')
    print(f'合计: {total_before} → {total_before + total_add} 条 (+{total_add})'
          f'{"[dry-run]" if args.dry_run else ""}')
    return 0


if __name__ == '__main__':
    sys.exit(main())
